#!/bin/sh
#
# Write the device side of the Claude engine: engines/claude/engine.
#
# The Kobo cannot run the daemon, so its "engine" is a shell script that hands
# the pipe to whichever netcat the device happens to have. engines.lua finds
# it the same way it finds Stockfish -- a folder with an executable in it --
# and engine_uci.lua execs it and talks UCI down the pipe, none the wiser that
# the other end is a tailnet away.
#
# The host and port are baked in here rather than read from a config file,
# because the alternative is a config file on a device that is awkward to edit
# and easy to forget. Run this again to point it somewhere else.
#
#   tools/make_claude_engine.sh 100.64.0.10 [9666]
#   ./install.sh root@<kobo> --engine claude
#
# engines/ is not tracked, so what this writes stays on this machine and on
# the device, like Stockfish.

set -eu

HOST="${1:-}"
PORT="${2:-9666}"

if [ -z "$HOST" ]; then
    echo "usage: $0 <host-or-tailnet-ip> [port]" >&2
    echo "  the address of the machine running tools/claude_engine.py" >&2
    exit 2
fi

ROOT=$(cd "$(dirname "$0")/.." && pwd)
DIR="$ROOT/kobochess.koplugin/engines/claude"
mkdir -p "$DIR"

cat > "$DIR/engine" <<EOF
#!/bin/sh
# KoboChess: Claude, played over the network. Generated by
# tools/make_claude_engine.sh -- edit that, not this.
#
# stdin and stdout are the plugin's UCI pipes; all this does is point them at
# the daemon. Which netcat exists varies between firmwares, so try them in
# turn. Failing to connect exits, the pipe closes, and the plugin reports that
# the engine stopped -- which is the truth, and better than hanging the board.
HOST=$HOST
PORT=$PORT

if command -v nc >/dev/null 2>&1; then
    exec nc "\$HOST" "\$PORT"
elif command -v ncat >/dev/null 2>&1; then
    exec ncat "\$HOST" "\$PORT"
elif command -v socat >/dev/null 2>&1; then
    exec socat - "TCP:\$HOST:\$PORT"
elif command -v busybox >/dev/null 2>&1; then
    exec busybox nc "\$HOST" "\$PORT"
fi

echo "KoboChess: no nc, ncat, socat or busybox on this device" >&2
exit 127
EOF

chmod +x "$DIR/engine"

echo "wrote $DIR/engine -> $HOST:$PORT"
echo
echo "next:"
echo "  1. start the daemon on $HOST:"
echo "       ~/.local/share/kobochess-claude-engine/venv/bin/python \\"
echo "           $ROOT/tools/claude_engine.py --port $PORT"
echo "  2. install it:"
echo "       ./install.sh root@<kobo-ip> --engine claude"
echo "  3. on the device: Options -> Engine -> Claude"
